from pyspark.sql import SparkSession
from pyspark.sql.functions import col, current_timestamp, lit, broadcast, when
from pyspark.sql.types import DoubleType, StringType, TimestampType, DateType

def ingest_bronze(spark, input_path, output_path, run_date, run_id):
    # Read CSV with all columns as strings
    bronze_df = spark.read.format("csv").option("header", "true").load(input_path)
    
    # Add ingestion_timestamp, source_file, pipeline_run_id columns
    bronze_df = bronze_df.withColumn("ingestion_timestamp", current_timestamp()) \
                         .withColumn("source_file_path", lit(input_path)) \
                        .withColumn("pipeline_run_id", lit(run_id))
    
    # Cast transaction_timestamp to TimestampType
    bronze_df = bronze_df.withColumn("transaction_timestamp", col("transaction_timestamp").cast(TimestampType()))
    
    # Partition by transaction_date
    transaction_date = (bronze_df["transaction_timestamp"].cast(DateType()).alias("transaction_date"))
    bronze_df = bronze_df.withColumn("transaction_date", transaction_date)
    
    # Write Parquet partitioned by date
    bronze_df.write.partitionBy("transaction_date").parquet(output_path)

def transform_silver(spark, bronze_path, merchants_path, output_path, run_date):
    # Read Bronze Parquet with partition pruning on run_date
    bronze_df = spark.read.parquet(bronze_path).where(col("transaction_date") == run_date)
    

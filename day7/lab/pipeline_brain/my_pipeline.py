def build_merchant_performance(spark, silver_path, output_path, run_date):
    # Read Silver layer data
    silver_df = spark.read.parquet(silver_path).filter(col("status") == "COMPLETED")
    
    # Define schema for merchant performance
    merchant_performance_schema = StructType([
        StructField("merchant_id", StringType(), True),
        StructField("merchant_name", StringType(), True),
        StructField("category", StringType(), True),
        StructField("city", StringType(), True),
        StructField("date", TimestampType(), True),
        StructField("total_revenue", DoubleType(), True),
        StructField("txn_count", IntegerType(), True),
        StructField("failure_rate_pct", DoubleType(), True)
    ])
    
    # Calculate metrics
    merchant_performance_df = silver_df.groupBy("merchant_id", "merchant_name", "category", "city", "transaction_date") \
        .agg(
            sum("amount").alias("total_revenue"),
            count("*").alias("txn_count"),
            count(when(col("status") == "FAILED", 1)).alias("failed_txns")
        )
    
    # Calculate failure rate percentage
    merchant_performance_df = merchant_performance_df.withColumn(
        "failure_rate_pct", 
        (col("failed_txns") / col("txn_count") * 100).cast(DoubleType())
    )
    
    # Rename transaction_date to date and cast to timestamp
    merchant_performance_df = merchant_performance_df.withColumnRenamed("transaction_date", "date") \
       .withColumn("date", expr("to_timestamp(date)"))
    
    # Write to output path partitioned by date
    merchant_performance_df.write.partitionBy("date").mode("overwrite").parquet(output_path)

def build_customer_ltv(spark, silver_path, output_path):
    # Read Silver layer data
    silver_df = spark.read.parquet(silver_path).filter(col("status") == "COMPLETED")
    
    # Define schema for customer LTV
    customer_ltv_schema = StructType([
        StructField("customer_id", StringType(), True),
        StructField("total_spent", DoubleType(), True),
        StructField("total_txns", IntegerType(), True),
        StructField("avg_txn_value", DoubleType(), True),
        StructField("first_txn_date", TimestampType(), True),
        StructField("last_txn_date", TimestampType(), True),
        StructField("preferred_payment_method", StringType(), True)
    ])
    
    # Calculate metrics
    customer_ltv_df = silver_df.groupBy("customer_id") \
        .agg(
            sum("amount").alias("total_spent"),
            count("*").alias("total_txns"),
            expr("AVG(amount)").alias("avg_txn_value"),
            min("transaction_timestamp").alias("first_txn_date"),
            max("transaction_timestamp").alias("last_txn_date")
        )
    
    # Determine preferred payment method (mode)
    from pyspark.sql.functions import collect_set, size, sort_array, first
    payment_method_counts = silver_df.groupBy("customer_id", "payment_method") \
       .agg(count("*").alias("count")) \
       .groupBy("customer_id") \
       .agg(collect_set(struct("payment_method", "count")).alias("payment_method_counts")) \
        .withColumn("payment_method_counts", sort_array(col("payment_method_counts"), ascending=False)) \
        .withColumn("preferred_payment_method", first(col("payment_method_counts.payment_method")))
    
    # Join with customer LTV DataFrame
    customer_ltv_df = customer_ltv_df.join(payment_method_counts, "customer_id", "left")
    
    # Write to output path
    customer_ltv_df.write.mode("overwrite").parquet(output_path)

